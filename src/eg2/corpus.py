"""Loading a folder of text files into something you can index.

The capstone lesson needs to go beyond a hardcoded list in the script: real
retrieval starts from real files sitting in a folder, and that introduces
concerns a hand-written corpus list never has -- encoding, extensions, recursion,
filenames doubling as titles, and documents too long to fit in one vector.

Standard library only, so loading a corpus works even on a machine with no
model installed.
"""

from __future__ import annotations

from pathlib import Path
from typing import Iterable, Sequence

DEFAULT_EXTENSIONS = (".md", ".txt")

#: Extensions to skip even when asked for. Generated by lessons at runtime and
#: never part of a corpus.
_SKIP_DIRS = {"__pycache__", ".git", ".ipynb_checkpoints", "node_modules", ".venv", "venv"}


def load_folder(
    path: str,
    extensions: Sequence[str] = DEFAULT_EXTENSIONS,
    recursive: bool = True,
    title_from: str = "name",
) -> list[dict]:
    """Read every matching file in a folder into indexable documents.

    Args:
        path: Folder to read.
        extensions: File suffixes to include.
        recursive: Descend into subfolders.
        title_from: ``"name"`` uses the filename stem, ``"heading"`` uses the
            first Markdown ``#`` line, falling back to the stem. Headings make
            much better document titles than snake_case filenames, and the model
            was trained to expect a meaningful ``title:``.

    Returns:
        A list of dicts with keys: title, text, path. Sorted by path, so the
        ordering is stable across runs.
    """
    root = Path(path)
    if not root.exists():
        raise FileNotFoundError(f"No such folder: {root}")
    if not root.is_dir():
        raise NotADirectoryError(f"Not a folder: {root}")

    pattern = "**/*" if recursive else "*"
    wanted = {e.lower() for e in extensions}

    documents: list[dict] = []
    for file_path in sorted(root.glob(pattern)):
        if not file_path.is_file():
            continue
        if file_path.suffix.lower() not in wanted:
            continue
        if any(part in _SKIP_DIRS for part in file_path.parts):
            continue

        try:
            # utf-8 first; files on Windows are sometimes not.
            text = file_path.read_text(encoding="utf-8")
        except UnicodeDecodeError:
            text = file_path.read_text(encoding="latin-1")

        text = text.strip()
        if not text:
            continue

        stem = file_path.stem
        title = _heading_title(text) if title_from == "heading" else stem
        documents.append(
            {
                "title": title or stem,
                "text": text,
                "path": str(file_path),
            }
        )

    return documents


def _heading_title(text: str) -> str:
    """First Markdown H1, or '' if there isn't one."""
    for line in text.splitlines():
        stripped = line.strip()
        if stripped.startswith("# "):
            return stripped[2:].strip()
        if stripped.startswith("#"):
            # A non-H1 heading further down is not the document title.
            break
    return ""


def chunk_text(text: str, max_chars: int = 1200, overlap: int = 150) -> list[str]:
    """Split a long document into overlapping chunks.

    Why chunk at all: the model accepts 8,192 tokens, and a document longer than
    that is truncated SILENTLY. You get a vector describing the first chunk and
    nothing tells you. Lesson L05 shows how to check the cost before encoding.

    Args:
        text: The full document.
        max_chars: Approximate chunk size. 1,200 characters is roughly 300
            tokens, which leaves plenty of room for a query prefix.
        overlap: Characters repeated between neighbours so a sentence spanning
            a boundary still appears whole in one of the two chunks.

    Returns:
        A list of chunks. Always at least one, even for short documents.
    """
    text = text.strip()
    if not text:
        return []
    if len(text) <= max_chars:
        return [text]

    chunks: list[str] = []
    start = 0
    length = len(text)

    while start < length:
        end = min(start + max_chars, length)

        if end < length:
            # Prefer to break at a paragraph, then a sentence, then a space.
            window = text[start:end]
            for separator in ("\n\n", "\n", ". ", " "):
                position = window.rfind(separator)
                if position > max_chars // 2:
                    end = start + position + len(separator)
                    break

        chunk = text[start:end].strip()
        if chunk:
            chunks.append(chunk)

        if end >= length:
            break
        # Step forward by the non-overlapping part, not the whole chunk,
        # otherwise overlap > 0 would loop forever.
        start = max(end - overlap, start + 1)

    return chunks


def index_folder(
    path: str,
    max_chars: int = 1200,
    overlap: int = 150,
    **load_kwargs,
) -> list[dict]:
    """Load a folder and split every document into chunks.

    Each chunk becomes its own indexable unit and inherits its parent document's
    title, so a result can say which file it came from.

    Returns:
        A list of dicts with keys: title, text, path, chunk, chunks_total.
    """
    documents = load_folder(path, **load_kwargs)
    records: list[dict] = []

    for document in documents:
        chunks = chunk_text(document["text"], max_chars, overlap)
        for position, chunk in enumerate(chunks, start=1):
            records.append(
                {
                    "title": document["title"],
                    "text": chunk,
                    "path": document["path"],
                    "chunk": position,
                    "chunks_total": len(chunks),
                }
            )

    return records


def summarise(records: Sequence[dict]) -> dict:
    """Small report about an index, for printing at a glance."""
    sources = {record["path"] for record in records}
    multi_chunk = sum(1 for r in records if r.get("chunks_total", 1) > 1)
    return {
        "files": len(sources),
        "chunks": len(records),
        "average_chunks_per_file": len(records) / len(sources) if sources else 0.0,
        "multi_chunk_files": multi_chunk,
        "total_characters": sum(len(r["text"]) for r in records),
    }


def file_names(records: Iterable[dict]) -> list[str]:
    """Distinct source paths, in first-seen order."""
    seen: list[str] = []
    for record in records:
        if record["path"] not in seen:
            seen.append(record["path"])
    return seen